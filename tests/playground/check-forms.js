async page => {
  const checks=[];
  const assert=(value,message)=>{if(!value)throw new Error(message);checks.push(message);};
  const base=new URL(page.url()).origin;
  const submit=async name=>{const response=page.waitForResponse(r=>r.url().includes('/feedback')&&r.request().method()==='POST');await page.getByRole('button',{name,exact:true}).click();return await(await response).json();};
  await page.goto(base+'/playground-multi-step-and-conditional/');
  await page.getByRole('button',{name:'Next',exact:true}).click();
  assert(await page.locator('.cf7m-step.active').getAttribute('data-step')==='1','Empty required fields prevent advancing');
  await page.getByRole('textbox',{name:'Your name',exact:true}).fill('Browser Fixture');
  await page.getByRole('textbox',{name:'Your email',exact:true}).fill('bad-email');
  await page.getByRole('button',{name:'Next',exact:true}).click();
  assert(await page.locator('.cf7m-step.active').getAttribute('data-step')==='1','Invalid email prevents advancing');
  await page.getByRole('textbox',{name:'Your email',exact:true}).fill('fixture@example.test');
  await page.getByRole('textbox',{name:'Your email',exact:true}).press('Enter');
  await page.waitForFunction(()=>document.querySelector('.cf7m-step.active').dataset.step==='2');
  assert(await page.locator('[name=support-details]').isDisabled(),'General reason hides and disables Support details');
  const general=await submit('Send request');
  assert(general.status==='mail_sent','A hidden required conditional field does not block submission');
  await page.goto(base+'/playground-multi-step-and-conditional/');
  await page.getByRole('textbox',{name:'Your name',exact:true}).fill('Support Browser Fixture');
  await page.getByRole('textbox',{name:'Your email',exact:true}).fill('fixture@example.test');
  await page.getByRole('combobox',{name:'Reason',exact:true}).selectOption('Support');
  await page.getByRole('button',{name:'Next',exact:true}).click();
  await page.getByRole('textbox',{name:'Support details',exact:true}).waitFor();
  const missing=await submit('Send request');
  assert(missing.status==='validation_failed' && missing.invalid_fields.some(field=>field.field==='support-details'),'Visible conditional fields remain required on the server');
  await page.getByRole('textbox',{name:'Support details',exact:true}).fill('Local fixture support request');
  assert((await submit('Send request')).status==='mail_sent','Filled visible conditional form submits successfully');
  await page.goto(base+'/playground-save-and-continue/');
  await page.getByRole('textbox',{name:'Your name',exact:true}).fill('Saved Browser Fixture');
  await page.getByRole('textbox',{name:'Your email',exact:true}).fill('fixture@example.test');
  await page.getByRole('textbox',{name:'Project details',exact:true}).fill('Retain this progress across reloads');
  await page.getByRole('combobox',{name:'Reason',exact:true}).selectOption('Support');
  await page.getByRole('textbox',{name:'Support details',exact:true}).fill('Restore dependent fields');
  await page.getByRole('listbox',{name:'Interests',exact:true}).selectOption(['Design','Support']);
  await page.getByRole('checkbox').uncheck();
  const token=await page.locator('[name=_cf7m_ps_token]').inputValue();
  const save=page.waitForResponse(r=>r.url().endsWith('/partial-save')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Save progress',exact:true}).click();
  assert((await save).ok(),'Save-and-continue writes progress through its public API');
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('[name=your-name]').value==='Saved Browser Fixture');
  assert(await page.getByRole('textbox',{name:'Support details',exact:true}).isVisible(),'Restored controlling value updates conditional visibility');
  assert((await page.locator('[name="interests[]"]').evaluate(el=>Array.from(el.selectedOptions,o=>o.value))).join(',')==='Design,Support','Multiple selected values survive save-and-continue');
  assert(!await page.getByRole('checkbox').isChecked(),'An unchecked default checkbox survives save-and-continue');
  assert((await submit('Submit project')).status==='mail_sent','Restored form can be submitted');
  assert(await page.locator('[name=_cf7m_ps_token]').inputValue()!==token,'Successful submission rotates the saved-progress token');
  const old=await page.evaluate(async token=>await(await fetch(cf7mPartialSave.root+'/partial-save/'+token,{headers:{'X-WP-Nonce':cf7mPartialSave.nonce}})).json(),token);
  assert(!old.found,'Successful submission removes saved progress');
  await page.goto(base+'/playground-closed-registration/');
  assert(await page.getByText('Registration is closed. Please try our contact form.',{exact:true}).isVisible() && await page.locator('form.wpcf7-form input[name=your-name]').count()===0,'Scheduled closed form displays its message and no fields');
  await page.screenshot({path:'output/playwright/playground-closed.png',fullPage:true});
  return checks;
}
