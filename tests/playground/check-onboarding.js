async page => {
  const checks = [];
  const assert = (value, message) => { if (!value) throw new Error(message); checks.push(message); };
  const base = new URL(page.url()).origin;
  await page.goto(base + '/wp-admin/admin.php?page=cf7-mate');
  const tick = async (scope, name, on) => { const box = scope.getByRole('checkbox', {name, exact:true}); if ((await box.isChecked()) !== on) await scope.locator('label').filter({has: page.getByRole('checkbox', {name, exact:true})}).click(); };
  const state = () => page.evaluate(async () => await wp.apiFetch({path:'/cf7mate-playground/v1/state'}));
  const fresh = await state();
  assert(['database_entries','analytics','webhook','partial_save'].every(key => fresh.features[key] === false), 'Fresh install leaves collection and sending opt-in');
  const card = page.getByRole('region', {name:'What should CF7 Mate collect?', exact:true});
  await card.waitFor();
  assert(await page.getByRole('dialog').count() === 0 && await page.locator('#cf7m-setup-notice, .notice:has-text("Run Setup Wizard")').count() === 0, 'Setup is an inline card, not a modal or admin notice');
  assert(await page.getByRole('heading', {name:'Features', exact:true}).isVisible(), 'Features stay usable below the setup card');
  const list = page.locator('main .grid').last();
  const iconSaved = page.waitForResponse(r => r.url().includes('/settings/features') && r.request().method() === 'POST');
  await tick(list, 'Icon', false);
  assert((await iconSaved).ok(), 'A feature outside the card saves on its own');
  for (const name of ['Form responses','Form analytics','Webhooks']) await tick(card, name, true);
  assert(!await card.getByRole('checkbox', {name:'Save and continue', exact:true}).isChecked(), 'Unchosen opt-in features stay off');
  await card.getByRole('button', {name:'Continue', exact:true}).click();
  const step2 = page.getByRole('region', {name:'Build forms with your AI', exact:true});
  await step2.waitFor();
  assert(await step2.getByRole('link', {name:/^(Get|Open) Saddle$/}).count() === 1 && await step2.getByRole('link', {name:'Saddle Analytics', exact:true}).count() === 1, 'Setup introduces optional Saddle and Saddle Analytics without installing anything');
  await page.route('**/admin-ajax.php', route => (route.request().postData() || '').includes('cf7m_complete_onboarding') ? route.fulfill({status:200, contentType:'application/json', body:JSON.stringify({success:false})}) : route.continue());
  await step2.getByRole('button', {name:'Finish', exact:true}).click();
  await step2.getByRole('alert').filter({hasText:'Could not save your setup.'}).waitFor();
  assert(await step2.isVisible() && !(await state()).onboarding_completed, 'A failed save keeps the card open for a retry');
  await page.unrouteAll({behavior:'wait'});
  let release;
  const gate = new Promise(resolve => { release = resolve; });
  await page.route('**/admin-ajax.php', async route => { if ((route.request().postData() || '').includes('cf7m_complete_onboarding')) await gate; await route.continue(); });
  await step2.getByRole('button', {name:'Finish', exact:true}).click();
  assert(await step2.getByRole('button', {name:'Finish', exact:true}).isDisabled(), 'Finish waits for the save and blocks double clicks');
  release();
  await step2.waitFor({state:'detached'});
  await page.getByRole('status').filter({hasText:'All set'}).waitFor();
  assert(await page.getByRole('dialog').count() === 0, 'Setup ends with a small popup, not a modal');
  await page.unrouteAll({behavior:'wait'});
  const saved = await state();
  assert(!!saved.onboarding_completed && ['database_entries','analytics','webhook'].every(key => saved.features[key]) && saved.features.partial_save === false && saved.features.icon === false, 'Setup stores chosen and unchosen features and keeps unrelated choices');
  await page.reload();
  await page.getByRole('heading', {name:'Features', exact:true}).waitFor();
  assert(await page.getByRole('region', {name:'What should CF7 Mate collect?', exact:true}).count() === 0, 'Finished setup does not return on its own');
  await page.getByText('Help', {exact:true}).click();
  await page.getByRole('link', {name:'Run setup again', exact:true}).click();
  const again = page.getByRole('region', {name:'What should CF7 Mate collect?', exact:true});
  await again.waitFor();
  await tick(again, 'Save and continue', true);
  await again.getByRole('button', {name:'Continue', exact:true}).click();
  await page.getByRole('button', {name:'Finish', exact:true}).click();
  await page.getByRole('status').filter({hasText:'All set'}).waitFor();
  const rerun = await state();
  assert(['database_entries','analytics','webhook','partial_save'].every(key => rerun.features[key]), 'Setup can run again from Help');
  await tick(list, 'Icon', true);
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({width, height:900});
    await page.screenshot({path:`output/playwright/refresh-features-${width}.png`, fullPage:true});
  }
  await page.setViewportSize({width:1440, height:1000});
  return checks;
}
