async page => {
  const checks = [];
  const assert = (value, message) => { if (!value) throw new Error(message); checks.push(message); };
  const base = new URL(page.url()).origin;
  await page.goto(base + '/wp-admin/admin.php?page=cf7-mate');
  await page.getByRole('heading', {name:'Features', exact:true}).waitFor();
  const setup = await page.evaluate(async () => ({nonce:dcsCF7Styler.nonce, features:(await wp.apiFetch({path:'/cf7-styler/v1/settings/features'})).features}));
  const flags = {...setup.features, database_entries:false, redirect:true, email_routing:true, form_scheduling:true, partial_save:true};
  try {
    await page.evaluate(async features => await wp.apiFetch({path:'/cf7-styler/v1/settings/features', method:'POST', data:{features}}), flags);
    const form = await page.evaluate(async () => await wp.apiFetch({path:'/contact-form-7/v1/contact-forms', method:'POST', data:{context:'save', title:'Editor design QA', form:'<label>Name [text* your-name]</label><label>Email [email* your-email]</label><label>Department [select department "General" "Support"]</label>[submit "Send"]'}}));
    if (!form.id) throw new Error('The fixture form was not saved.');
    await page.goto(base + '/wp-admin/admin.php?page=wpcf7&post=' + form.id + '&action=edit');
    const nativeStylesUnchanged = await page.evaluate(() => {
      const sheet = Array.from(document.styleSheets).find(item => item.href && item.href.includes('/cf7m-editor-panel.css'));
      if (!sheet) return false;
      const nodes = document.querySelectorAll('#contact-form-editor, #contact-form-editor-tabs, #contact-form-editor-tabs [role=tab], #form-panel, #mail-panel, #messages-panel, #additional-settings-panel, #wpcf7-form, #tag-generator-list, #tag-generator-list button, #tag-generator-list a');
      const snapshot = () => Array.from(nodes, node => {
        const style = getComputedStyle(node);
        return Array.from(style, key => [key, style.getPropertyValue(key)]);
      });
      const enhanced = JSON.stringify(snapshot());
      sheet.disabled = true;
      const native = JSON.stringify(snapshot());
      sheet.disabled = false;
      return enhanced === native;
    });
    assert(nativeStylesUnchanged, 'CF7 Mate styles leave native editor tabs, panels, textarea and tag buttons unchanged');
    assert(await page.locator('.cf7m-field-tools').count() === 0 && await page.locator('#tag-generator-list > [data-target=tag-generator-panel-cf7m-step], #tag-generator-list > a[href*="inlineId=tag-generator-panel-cf7m-step"]').count() === 1, 'Native Form field tools retain their original placement');
    await page.getByRole('tab', {name:'CF7 Mate', exact:true}).click();
    await page.locator('.cf7m-editor-nav button').first().waitFor();
    assert(await page.locator('[data-cf7m-section=responses]').count() === 0 && await page.locator('.cf7m-editor-nav button').count() === 4, 'Form settings remain accessible with response storage off');
    await page.locator('.cf7m-editor-nav button').filter({hasText:'After submission'}).click();
    assert(!await page.locator('[name=cf7m_redirect_enabled]').isChecked() && await page.locator('[name=cf7m_redirect_url]').isHidden(), 'Disabled redirects hide their configuration');
    await page.locator('[name=cf7m_redirect_enabled]').check();
    await page.locator('[name=cf7m_redirect_url]').fill('/thank-you/');
    await page.locator('[name=cf7m_redirect_delay_ms]').fill('500');
    await page.locator('#cf7m-add-redirect-rule').click();
    await page.locator('[name="cf7m_redirect_field[]"]').fill('department');
    await page.locator('[name="cf7m_redirect_value[]"]').fill('Support');
    await page.locator('[name="cf7m_redirect_target[]"]').fill('/support-thanks/');
    assert(await page.locator('[name="cf7m_redirect_field[]"]').getAttribute('list') === 'cf7m-form-fields' && await page.locator('#cf7m-form-fields option[value=department]').count() === 1, 'Rule fields suggest tags from the current form');
    assert((await page.locator('.cf7m-editor-save-status').innerText()).includes('Unsaved changes'), 'Form settings show that edits still need the native Save action');
    await page.locator('.cf7m-editor-nav button').filter({hasText:'Email routing'}).click();
    assert(await page.locator('[data-cf7m-section=routing] .cf7m-rules-empty').isVisible(), 'Routing starts with an explanatory empty state');
    await page.locator('#cf7m-add-rule').click();
    await page.locator('[name="cf7m_route_field[]"]').fill('department');
    await page.locator('[name="cf7m_route_value[]"]').fill('Support');
    await page.locator('[name="cf7m_route_emails[]"]').fill('support@example.test');
    await page.locator('#cf7m-add-rule').click();
    await page.locator('#cf7m-routing-rows .cf7m-remove-rule').last().click();
    assert(await page.locator('#cf7m-routing-rows tr').count() === 1, 'Routing rules can be added and removed');
    await page.locator('.cf7m-editor-nav button').filter({hasText:'Scheduling'}).click();
    await page.locator('[name=cf7m_schedule_enabled]').check();
    await page.locator('[name=cf7m_schedule_start]').fill('2026-01-01T08:00');
    await page.locator('[name=cf7m_schedule_end]').fill('2030-12-31T18:00');
    await page.locator('[name=cf7m_schedule_msg]').fill('This registration is closed.');
    await page.locator('[name=cf7m_schedule_enabled]').uncheck();
    assert(await page.locator('[name=cf7m_schedule_end]').isHidden() && await page.locator('[name=cf7m_schedule_end]').inputValue() === '2030-12-31T18:00', 'Hiding scheduling controls retains their values');
    await page.locator('[name=cf7m_schedule_enabled]').check();
    await page.locator('.cf7m-editor-nav button').filter({hasText:'Save progress'}).click();
    await page.locator('[name=cf7m_partial_save_enabled]').check();
    const saved = page.waitForNavigation({waitUntil:'load'});
    await page.getByRole('button', {name:'Save', exact:true}).first().click();
    await saved;
    await page.getByRole('tab', {name:'CF7 Mate', exact:true}).click();
    assert(await page.locator('[name=cf7m_partial_save_enabled]').isChecked(), 'Save progress persists through the native form save');
    await page.locator('.cf7m-editor-nav button').filter({hasText:'After submission'}).click();
    assert(await page.locator('[name=cf7m_redirect_enabled]').isChecked() && await page.locator('[name=cf7m_redirect_url]').inputValue() === '/thank-you/' && await page.locator('[name="cf7m_redirect_target[]"]').inputValue() === '/support-thanks/', 'Redirect settings and rules survive saving from another section');
    await page.locator('.cf7m-editor-nav button').filter({hasText:'Email routing'}).click();
    assert(await page.locator('[name="cf7m_route_emails[]"]').inputValue() === 'support@example.test', 'Routing settings survive saving from another section');
    await page.locator('.cf7m-editor-nav button').filter({hasText:'Scheduling'}).click();
    assert(await page.locator('[name=cf7m_schedule_enabled]').isChecked() && await page.locator('[name=cf7m_schedule_end]').inputValue() === '2030-12-31T18:00', 'Schedule dates and enabled state persist');
    await page.screenshot({path:'output/playwright/redesign-editor-scheduling.png', fullPage:true});
    await page.getByRole('tab', {name:'Form', exact:true}).click();
    await page.locator('[data-target=tag-generator-panel-cf7m-step],a[href*="inlineId=tag-generator-panel-cf7m-step"]').click();
    await page.locator('#tag-generator-panel-cf7m-step:visible, #TB_window form[data-id=cf7m-step]').waitFor({state:'visible'});
    assert(true, 'Unchanged native field tools still open their tag generators');
    await page.keyboard.press('Escape');
    if (await page.locator('#TB_closeWindowButton').isVisible()) await page.locator('#TB_closeWindowButton').click();
    await page.getByRole('tab', {name:'CF7 Mate', exact:true}).click();
    await page.setViewportSize({width:390, height:844});
    await page.screenshot({path:'output/playwright/redesign-editor-mobile.png', fullPage:true});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Form editor fits a mobile viewport without page overflow');
  } finally {
    await page.request.post(base+'/wp-json/cf7-styler/v1/settings/features', {data:{features:setup.features}, headers:{'X-WP-Nonce':setup.nonce}});
    await page.setViewportSize({width:1440, height:1000});
  }
  return checks;
}
