async page => {
  const checks=[];
  const assert=(value,message)=>{if(!value)throw new Error(message);checks.push(message);};
  const base=new URL(page.url()).origin;
  await page.goto(base+'/wp-admin/admin.php?page=cf7-mate');
  await page.getByRole('navigation',{name:'CF7 Mate navigation'}).getByRole('link',{name:'Tools',exact:true}).click();
  await page.getByRole('button',{name:'Save',exact:true}).first().waitFor();
  if (await page.getByRole('button',{name:'Remove API key',exact:true}).count()) await page.getByRole('button',{name:'Remove API key',exact:true}).click();
  await page.getByPlaceholder('sk-...').fill('sk-playground-fixture');
  const saved=page.waitForResponse(r=>r.url().includes('/ai-settings')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Save',exact:true}).first().click();
  assert((await saved).ok(),'AI provider settings save without a license');
  const tested=page.waitForResponse(r=>r.url().includes('/ai-settings/test'));
  await page.getByRole('button',{name:'Test connection',exact:true}).click();
  assert((await(await tested).json()).success,'AI connection test reaches the local provider sink');
  const existingUrls=await page.evaluate(async()=>await wp.apiFetch({path:'/cf7-styler/v1/settings/webhook'}));
  if (!existingUrls.urls.includes('https://example.com/cf7mate-playground')) {
  await page.getByRole('textbox',{name:'Webhook URL',exact:true}).fill('https://example.com/cf7mate-playground');
  await page.getByRole('button',{name:'Add',exact:true}).click();
  const urls=page.waitForResponse(r=>r.url().includes('/settings/webhook')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Save',exact:true}).last().click();
  assert((await urls).ok(),'Webhook destinations save in Tools');
  } else assert(true,'Webhook destination remains saved in Tools');
  await page.goto(base+'/wp-admin/admin.php?page=wpcf7&post=5&action=edit');
  const originalMarkup=await page.locator('#wpcf7-form').inputValue();
  await page.getByRole('button',{name:'AI Generate',exact:true}).click();
  await page.getByRole('textbox',{name:'Describe your form',exact:true}).fill('Create a name, email and message contact form.');
  const generated=page.waitForResponse(r=>r.url().includes('/ai-generate')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Generate',exact:true}).click();
  assert((await generated).ok(),'AI generation completes through the local provider sink');
  await page.getByRole('textbox',{name:'Form code',exact:true}).waitFor();
  assert((await page.getByRole('textbox',{name:'Form code',exact:true}).inputValue()).includes('[email* your-email]'),'AI result contains editable CF7 form markup');
  await page.getByRole('button',{name:'Insert',exact:true}).click();
  assert((await page.locator('#wpcf7-form').inputValue()).includes('[email* your-email]'),'Generated markup inserts into the CF7 editor');
  // Leave the saved fixture markup intact; inserting is an editor-only draft.
  await page.locator('#wpcf7-form').fill(originalMarkup);
  // Discard the draft: CF7 5.x asks before leaving an edited form, which would block the run.
  await page.evaluate(()=>{window.onbeforeunload=null;if(window.jQuery)window.jQuery(window).off('beforeunload');});
  await page.goto(base+'/playground-contact/');
  await page.getByRole('textbox',{name:'Your name',exact:true}).fill('Admin Browser Fixture');
  await page.getByRole('textbox',{name:'Your email',exact:true}).fill('fixture@example.test');
  await page.getByRole('textbox',{name:'Message',exact:true}).fill('Local response and webhook smoke test');
  const submitted=page.waitForResponse(r=>r.url().includes('/feedback')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Send message',exact:true}).click();
  assert((await(await submitted).json()).status==='mail_sent','Contact form submits with mail intercepted locally');
  await page.goto(base+'/wp-admin/admin.php?page=cf7-mate-responses');
  await page.getByRole('link',{name:'View',exact:true}).first().waitFor();
  assert(await page.getByText('Admin Browser Fixture',{exact:false}).count()>0,'Responses list shows the actual submitted fixture');
  const downloaded=page.waitForEvent('download');
  await page.getByRole('link',{name:'Export',exact:true}).filter({has:page.locator('svg')}).click();
  const download=await downloaded;
  await download.saveAs('output/playwright/playground-responses.csv');
  assert(!await download.failure(),'CSV export downloads successfully');
  await page.getByRole('link',{name:'View',exact:true}).first().click();
  const printLink=page.getByRole('link',{name:'Print / Save PDF',exact:true});
  await printLink.waitFor();
  const print=await page.request.get(await printLink.getAttribute('href'));
  assert(print.ok()&&(await print.text()).includes('Admin Browser Fixture'),'Printable response contains stored submission data');
  await page.screenshot({path:'output/playwright/playground-response.png',fullPage:true});
  await page.goto(base+'/wp-admin/admin.php?page=cf7-mate-analytics');
  await page.getByRole('heading',{name:'Analytics',exact:true}).waitFor();
  const stats=await page.evaluate(async()=>await wp.apiFetch({path:'/cf7-styler/v1/analytics/stats'}));
  assert(stats.some(row=>row.form_id===5&&row.views>0&&row.submissions>0),'Analytics records local views and stored submissions');
  await page.goto(base+'/wp-admin/admin.php?page=cf7-mate-saddle');
  await page.getByRole('heading',{name:'Saddle',exact:true}).waitFor();
  assert(await page.getByRole('heading',{name:'Quick MCP setup',exact:true}).count()===1,'Saddle submenu explains connection setup');
  assert(await page.getByRole('link',{name:'White label',exact:true}).count()===0,'Retired white label is absent');
  assert(await page.getByRole('link',{name:'Get Saddle Analytics',exact:true}).count()===1,'Optional Saddle Analytics recommendation is available');
  assert(await page.getByRole('link',{name:'Community',exact:true}).count()===0,'Help keeps documentation and support only');
  assert(await page.locator('[id^="toplevel_page_wpcf7"]').evaluate(el=>el.classList.contains('wp-has-current-submenu')),'The Saddle tab keeps the Contact menu open');
  const state=await page.evaluate(async()=>await wp.apiFetch({path:'/cf7mate-playground/v1/state'}));
  assert(state.outbound_sink.some(item=>item.kind==='ai')&&state.outbound_sink.some(item=>item.kind==='webhook'),'AI and webhook activity is recorded by local sinks');
  return checks;
}
